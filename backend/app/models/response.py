from typing import Any, Dict, List, Optional, TYPE_CHECKING
from sqlalchemy import Boolean, ForeignKey, Integer, JSON, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base
from app.models.base import TimestampMixin, UUIDMixin

if TYPE_CHECKING:
    from app.models.experiment import Experiment
    from app.models.prompt import Prompt
    from app.models.evaluation import AutomatedEvaluation
    from app.models.annotation import HumanAnnotation
    from app.models.red_team_attempt import RedTeamAttempt


class ModelResponse(Base, UUIDMixin, TimestampMixin):
    """
    Stores the raw response generated by a target LLM for a given prompt within an experiment.
    """
    __tablename__ = "model_responses"

    experiment_id: Mapped[str] = mapped_column(String(36), ForeignKey("experiments.id", ondelete="CASCADE"), nullable=False, index=True)
    prompt_id: Mapped[str] = mapped_column(String(36), ForeignKey("prompts.id", ondelete="CASCADE"), nullable=False, index=True)
    
    response_text: Mapped[str] = mapped_column(Text, nullable=False)
    prompt_tokens: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    completion_tokens: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    latency_ms: Mapped[int] = mapped_column(Integer, default=0, nullable=False)

    # Safety Guardrail Interceptor fields
    guardrail_intervened: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    guardrail_details: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)

    # Relationships
    experiment: Mapped["Experiment"] = relationship("Experiment", back_populates="responses")
    prompt: Mapped["Prompt"] = relationship("Prompt", back_populates="responses")
    evaluation: Mapped[Optional["AutomatedEvaluation"]] = relationship("AutomatedEvaluation", back_populates="response", uselist=False, cascade="all, delete-orphan")
    annotations: Mapped[List["HumanAnnotation"]] = relationship("HumanAnnotation", back_populates="response", cascade="all, delete-orphan")
    red_team_attempts: Mapped[List["RedTeamAttempt"]] = relationship("RedTeamAttempt", back_populates="response", cascade="all, delete-orphan")

